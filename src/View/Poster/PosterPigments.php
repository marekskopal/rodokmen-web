namespace Rodokmen\Site\View\Poster;

/**
 * Colours of a medieval illuminator for the decoration of the historical poster: vermilion, lapis, verdigris and
 * gold (a base, a darker outline and a burnished highlight, as gold leaf cannot be printed).
 */
final readonly class PosterPigments
{
	public const Vermilion = '#a8402a';

	public const Lapis = '#34507a';

	public const Verdigris = '#4f7a55';

	public const Green = '#6d8f3f';

	public const Gold = '#c9a13b';

	public const GoldShade = '#7a5a1c';

	public const GoldLight = '#f1dc95';

	/** White lead, for flowers and highlights on a coloured ground. */
	public const White = '#f6ead0';
}
